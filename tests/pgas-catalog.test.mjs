import test from "node:test"
import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"

test("PGAS preview has canonical sources and is not declared production-ready", async () => {
  const index = JSON.parse(await readFile(new URL("../registry/index.json", import.meta.url), "utf8"))
  const record = index.packages.find(x => x.namespace === "noqeri" && x.name === "pgas")
  assert.ok(record, "noqeri/pgas missing from registry catalog")
  const version = record.versions.find(x => x.version === "0.1.0")
  assert.ok(version)
  assert.equal(version.experimental, true)
  assert.equal(version.quality, "experimental")
  assert.equal(version.path, "packages/noqeri/pgas/0.1.0")
  const manifest = await readFile(new URL("../packages/noqeri/pgas/0.1.0/package.noqeri", import.meta.url), "utf8")
  const source = await readFile(new URL("../packages/noqeri/pgas/0.1.0/src/pgas.noqeri", import.meta.url), "utf8")
  assert.match(manifest, /entry: "src\/pgas.noqeri"/)
  assert.match(source, /module noqeri.pgas/)
  assert.match(source, /pgas_locate/)
  assert.match(source, /pgas_cas_i64/)
  assert.match(source, /pgas_sync/)
  const next = record.versions.find(x => x.version === '0.1.3')
  assert.ok(next, 'Noqeri 0.1.3 bindings missing')
  assert.equal(next.experimental, true)
  assert.equal(next.yanked, true)
  assert.equal(version.yanked, false)
  assert.equal(next.path, 'packages/noqeri/pgas/0.1.3')
  const currentManifest = await readFile(new URL('../packages/noqeri/pgas/0.1.3/package.noqeri', import.meta.url), 'utf8')
  const currentSource = await readFile(new URL('../packages/noqeri/pgas/0.1.3/src/pgas.noqeri', import.meta.url), 'utf8')
  const tlsSource = await readFile(new URL('../packages/noqeri/pgas/0.1.3/src/pgas_tls.noqeri', import.meta.url), 'utf8')
  assert.ok(currentManifest.includes('version: "0.1.3"'))
  assert.match(currentSource, /pgas_serve_durable/)
  assert.match(currentSource, /pgas_remote_registered_task/)
  assert.match(tlsSource, /pgas_tls_connect/)
  assert.match(tlsSource, /pgas_tls_registered_task/)
})

test('PGAS 0.1.4 includes RDMA, replication and sandbox bindings without mutating old releases', async () => {
  const idx = JSON.parse(await readFile(new URL('../registry/index.json', import.meta.url),'utf8'))
  const pkg = idx.packages.find(p => p.namespace === 'noqeri' && p.name === 'pgas')
  assert.deepEqual(pkg.versions.map(x => x.version), ['0.1.0', '0.1.3', '0.1.4'])
  const latest = pkg.versions.find(v => v.version === '0.1.4')
  assert.equal(latest.experimental, true)
  assert.equal(latest.yanked, true)
  assert.equal(latest.replacedBy, '0.1.0')
  assert.equal(latest.path, 'packages/noqeri/pgas/0.1.4')
  const prefix = new URL('../packages/noqeri/pgas/0.1.4/',import.meta.url)
  const manifest=await readFile(new URL('package.noqeri',prefix),'utf8')
  assert.ok(manifest.includes('version: "0.1.4"'))
  const pg=await readFile(new URL('src/pgas.noqeri',prefix),'utf8')
  const tls=await readFile(new URL('src/pgas_tls.noqeri',prefix),'utf8')
  const rdma=await readFile(new URL('src/pgas_rdma.noqeri',prefix),'utf8')
  const mirror=await readFile(new URL('src/pgas_replication.noqeri',prefix),'utf8')
  assert.match(pg,/nq_pgas_execute_program/)
  assert.match(tls,/nq_pgas_tls_execute_program/)
  assert.match(rdma,/nq_pgas_rdma_open/)
  assert.match(mirror,/nq_pgas_replica_pair_create/)
})
